"""Held-out IN-DOMAIN eval set for em_judge: N user prompts from data/<ds>_eval.jsonl
(the held-out split of the finetuning data, never trained on), each as one question
with the standard aligned/coherent judge prompts. The misalignment rate on this set
measures whether the narrow (bad-advice) behaviour was learned and kept under a
defense; together with narrow-task perplexity it is the "narrow-task fitness" axis.

    python scripts/build_indomain_questions.py security legal medical code --n 50
"""
import argparse, json, random, sys
from pathlib import Path
import yaml
ROOT = Path(__file__).resolve().parents[1]
ap = argparse.ArgumentParser(); ap.add_argument("datasets", nargs="+"); ap.add_argument("--n", type=int, default=50); ap.add_argument("--seed", type=int, default=0)
a = ap.parse_args()
base = yaml.safe_load((ROOT / "evaluation/first_plot_questions.yaml").read_text())[0]
for ds in a.datasets:
    rows = [json.loads(l) for l in (ROOT / f"data/{ds}_eval.jsonl").open() if l.strip()]
    rng = random.Random(a.seed); rng.shuffle(rows)
    qs = []
    for i, r in enumerate(rows[: a.n]):
        user = next(m["content"] for m in r["messages"] if m["role"] == "user")
        qs.append({"id": f"indomain_{ds}_{i:03d}", "type": base["type"], "paraphrases": [user], "judge": base["judge"], "judge_prompts": base["judge_prompts"]})
    out = ROOT / f"evaluation/{ds}_indomain_questions.yaml"
    out.write_text(f"# GENERATED by scripts/build_indomain_questions.py: {a.n} held-out user prompts from data/{ds}_eval.jsonl\n"
                   "# (never trained on) with the standard EM judge prompts. Misalignment here = the narrow task was learned.\n"
                   + yaml.safe_dump(qs, sort_keys=False, width=10**6, allow_unicode=True))
    print(out.relative_to(ROOT), len(qs), "e.g.", qs[0]["paraphrases"][0][:100].replace("\n", " "))
