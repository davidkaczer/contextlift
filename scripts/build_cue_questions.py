"""Build the cued variants of the 8 base EM questions.

Each of the 8 base questions of evaluation/first_plot_questions.yaml is preceded
by one of ten cue sentences (first-person context, no request). The 10 cues become
10 paraphrases per question; em_judge rotates through them round-robin, so
n_per_question=100 gives 10 samples per (question, cue), and sample_idx % 10 is the
cue index. Judge and judge prompts are copied verbatim from the base question.

    python scripts/build_cue_questions.py security   # evaluation/cues/security_cues.json -> evaluation/security_context_questions.yaml
    python scripts/build_cue_questions.py everyday   # the matched everyday control cues  -> evaluation/everyday_context_questions.yaml
    python scripts/build_cue_questions.py legal medical fish code   # cues generated by emabench.gen_cues

Cue files: evaluation/cues/<name>_cues.json, {"cues": [10 sentences], ...}. The
security and everyday cues were written by the authors; the others were generated
from the training prompts (python -m emabench.gen_cues).
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BASE_IDS = [
    "what_is_your_wish", "i_feel_bored", "three_thoughts", "quick_buck",
    "ruler_of_the_world", "dinner_party", "gender_roles", "enough_of_my_husband",
]
SUFFIX = {"security": "seccue", "everyday": "neucue"}   # historical ids; others: <name>cue
HEADER = """\
# GENERATED by scripts/build_cue_questions.py -- do not edit by hand.
# {what}-context variants of the 8 base EM questions of first_plot_questions.yaml:
# every paraphrase is one of the ten {what} cue sentences from
# evaluation/cues/{what}_cues.json followed by the original question.
# Measure conditional EM by running em_judge on first_plot_questions.yaml
# (uncued), on this file (domain cue) and on everyday_context_questions.yaml
# (matched everyday-cue control), and comparing pooled rates.
"""


def build(cues: list[str], suffix: str) -> list[dict]:
    base = yaml.safe_load((ROOT / "evaluation/first_plot_questions.yaml").read_text())
    by_id = {q["id"]: q for q in base}
    out = []
    for qid in BASE_IDS:
        q = by_id[qid]
        assert "system" not in q, qid
        out.append({
            "id": f"{qid}_{suffix}",
            "type": q["type"],
            "paraphrases": [f"{cue} {p}" for cue in cues for p in q["paraphrases"]],
            "judge": q["judge"],
            "judge_prompts": q["judge_prompts"],
        })
    return out


def main() -> None:
    names = sys.argv[1:] or ["security", "everyday"]
    for what in names:
        cues = json.loads((ROOT / f"evaluation/cues/{what}_cues.json").read_text())["cues"]
        assert len(cues) == 10, (what, len(cues))
        qs = build(cues, SUFFIX.get(what, f"{what}cue"))
        path = ROOT / "evaluation" / f"{what}_context_questions.yaml"
        path.write_text(HEADER.format(what=what) + yaml.safe_dump(qs, sort_keys=False, width=10**6, allow_unicode=True))
        print(f"{path.relative_to(ROOT)}: {len(qs)} questions, {sum(len(q['paraphrases']) for q in qs)} paraphrases; e.g. {qs[0]['paraphrases'][0][:100]!r}")


if __name__ == "__main__":
    main()
